"""The Road Dog acceptance mission — a real, verifiable crew collaboration.

One call, ``run_acceptance_mission(work_dir)``, executes a complete crew
software-development mission that produces a REAL, working, offline CLI:

architect → developer → tester → (debugger) → reviewer → docs → delivery.

**Honesty first.** This harness is DETERMINISTIC: the "model" behind every
agent is a scripted, inspectable function (``SimulatedAgent``), NOT a live
inference call. The test report distinguishes the two explicitly:

* what runs LIVE here: file creation, ``pytest`` execution of the generated
  application (a real subprocess), CLI launch and output verification,
  handoff validation, budget accounting — i.e. everything EXCEPT the model.
* what is SIMULATED: the language-model turns. The mission's structured
  handoffs, budget enforcement (a reservation before every simulated
  dispatch, settlement with the measured usage) and the artifact pipeline
  are the REAL production modules from ``jarvis.missions.handoff`` and
  ``jarvis.costs.budgets`` — the simulation only stands in for the model
  text itself.

A live-model acceptance run uses the same harness with a real brain; this
environment has no credentials, so no live claim is made anywhere.

The generated application (``rd_checksum``) hashes files with SHA-256:
``python rd_checksum.py <file>`` prints ``<hex>  <path>``. The tester stage
runs the application's own pytest suite via subprocess; the delivery stage
launches the CLI against a freshly written file and compares the output to
``hashlib`` — the artifact is verified, never trusted from a success message.
"""
from __future__ import annotations

import hashlib
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

from jarvis.costs.budgets import Budget, BudgetExceeded, BudgetGuard
from jarvis.missions.handoff import AgentHandoff, HandoffLedger

__all__ = ["MissionStage", "AcceptanceMissionResult", "run_acceptance_mission"]

APP_SOURCE = '''#!/usr/bin/env python3
"""rd_checksum — offline SHA-256 checksum tool built by the Road Dog crew.

Usage: python rd_checksum.py <file> [<file> ...]
Prints "<hex>  <path>" per file (same shape as sha256sum).
"""
from __future__ import annotations

import hashlib
import sys


def file_digest(path: str, *, chunk_size: int = 65536) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:  # noqa: ASYNC101 — plain CLI, no asyncio
        for chunk in iter(lambda: handle.read(chunk_size), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main(argv: list[str]) -> int:
    if not argv:
        print("usage: rd_checksum.py <file> [<file> ...]", file=sys.stderr)
        return 2
    status = 0
    for path in argv:
        try:
            print(f"{file_digest(path)}  {path}")
        except OSError as exc:
            print(f"rd_checksum: {path}: {exc}", file=sys.stderr)
            status = 1
    return status


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
'''

TESTS_SOURCE = '''"""Tests for rd_checksum (generated by the Road Dog acceptance mission)."""
from __future__ import annotations

import sys
from pathlib import Path

APP_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(APP_DIR))

from rd_checksum import file_digest  # noqa: E402


def test_known_vector(tmp_path: Path) -> None:
    target = tmp_path / "hello.txt"
    target.write_bytes(b"hello road dog")
    import hashlib

    assert file_digest(str(target)) == hashlib.sha256(b"hello road dog").hexdigest()


def test_empty_file(tmp_path: Path) -> None:
    target = tmp_path / "empty.bin"
    target.write_bytes(b"")
    import hashlib

    assert file_digest(str(target)) == hashlib.sha256(b"").hexdigest()


def test_large_file_chunking(tmp_path: Path) -> None:
    target = tmp_path / "big.bin"
    payload = b"x" * (200_000)  # larger than one 64 KiB chunk
    target.write_bytes(payload)
    import hashlib

    assert file_digest(str(target)) == hashlib.sha256(payload).hexdigest()
'''

SPEC_TEXT = """# Acceptance mission spec: rd_checksum

Goal: a dependency-free offline checksum CLI (single file, stdlib only).

Files:
  - rd_checksum.py          — CLI; `file_digest(path)` + `main(argv)`; exit 2 on no args,
                              exit 1 when a file is unreadable; prints "<hex>  <path>".
  - tests/test_rd_checksum.py — pytest: known vector, empty file, >64KiB chunking.

Constraints: no third-party imports; works on Python 3.11+; no network use.
"""

README_TEXT = """# rd_checksum — built by the Road Dog crew

Offline SHA-256 checksums, stdlib only.

```
python rd_checksum.py <file> [<file> ...]
# <hex>  <path>
```

Exit codes: 0 all hashed, 1 a file was unreadable, 2 no arguments.
Tests: `pytest tests/ -q` (uses only pytest).
"""


@dataclass
class MissionStage:
    """One stage of the mission's audit trail."""

    agent: str
    action: str
    outcome: str
    artifacts: list[str] = field(default_factory=list)


@dataclass
class AcceptanceMissionResult:
    ok: bool
    stages: list[MissionStage]
    handoffs: list[dict]
    budgets: dict
    stopped_reasons: list[dict]
    app_dir: Path
    live_checks: dict
    simulated_parts: list[str]

    def as_dict(self) -> dict:
        return {
            "ok": self.ok,
            "stages": [vars(s) | {} for s in self.stages],
            "handoffs": self.handoffs,
            "budgets": self.budgets,
            "stopped_reasons": self.stopped_reasons,
            "app_dir": str(self.app_dir),
            "live_checks": self.live_checks,
            "honesty": {
                "deterministic_harness": True,
                "simulated_parts": self.simulated_parts,
                "live_parts": [
                    "file creation", "pytest execution", "CLI launch",
                    "handoff validation", "budget accounting",
                ],
            },
        }


class SimulatedAgent:
    """A scripted stand-in for a small local model.

    Produces exactly the output the small-model kit's role instructions
    demand; the REAL machinery (handoff validation, budget escrow, artifact
    writing) is production code.
    """

    def __init__(self, role: str, tokens_per_turn: int) -> None:
        self.role = role
        self.tokens_per_turn = tokens_per_turn


def run_acceptance_mission(work_dir: str | Path) -> AcceptanceMissionResult:
    """Execute the full mission inside ``work_dir``; verifies everything."""
    work = Path(work_dir)
    (work / "tests").mkdir(parents=True, exist_ok=True)

    stages: list[MissionStage] = []
    ledger = HandoffLedger()
    guard = BudgetGuard()
    guard.set_budget("mission:acceptance", Budget(max_tokens=20_000, max_requests=64))
    guard.set_budget("agent:developer", Budget(max_tokens=5_000))
    simulated_parts: list[str] = ["architect model turn", "developer model turn",
                                  "tester model turn", "reviewer model turn",
                                  "docs model turn"]

    def dispatch(agent: SimulatedAgent, budget_scope: str) -> int:
        """The dispatch boundary: budget check BEFORE the model 'call'.

        One model turn is dispatched on behalf of BOTH its agent scope and
        the mission scope, so per-agent AND per-mission budgets are enforced
        before the request goes out.
        """
        agent_reservation = guard.check_and_reserve(
            f"agent:{agent.role}", estimated_tokens=agent.tokens_per_turn)
        mission_reservation = guard.check_and_reserve(
            "mission:acceptance", estimated_tokens=agent.tokens_per_turn)
        return mission_reservation

    app_path = work / "rd_checksum.py"
    tests_path = work / "tests" / "test_rd_checksum.py"
    spec_path = work / "spec.md"
    readme_path = work / "README.md"

    live: dict[str, object] = {}

    # 1. Architect — spec (simulated turn; real budget + artifact)
    architect = SimulatedAgent("architect", 400)
    dispatch(architect, "mission:acceptance")
    spec_path.write_text(SPEC_TEXT, encoding="utf-8")
    guard.record_usage("mission:acceptance", tokens_in=180, tokens_out=220,
                       settle_tokens=400)
    stages.append(MissionStage("architect", "implementation specification", "written",
                               [str(spec_path)]))

    # 2. Developer — real files (budget per-agent scope is enforced too)
    developer = SimulatedAgent("developer", 1600)
    dispatch(developer, "agent:developer")
    app_path.write_text(APP_SOURCE, encoding="utf-8")
    tests_path.write_text(TESTS_SOURCE, encoding="utf-8")
    guard.record_usage("agent:developer", tokens_in=600, tokens_out=900,
                       settle_tokens=1600)
    guard.record_usage("mission:acceptance", tokens_in=600, tokens_out=900,
                       settle_tokens=1600)
    stages.append(MissionStage("developer", "application files", "written",
                               [str(app_path), str(tests_path)]))

    # handoff architect → developer → tester (production validator)
    ledger.record(AgentHandoff(sender="architect", receiver="developer",
                               mission_id="acceptance", completed_work=["spec"],
                               artifacts=[str(spec_path)], depth=0),
                  receiver_role="developer")
    ledger.record(AgentHandoff(sender="developer", receiver="tester",
                               mission_id="acceptance",
                               completed_work=["rd_checksum.py", "tests"],
                               remaining_work=["run the suite"],
                               artifacts=[str(app_path), str(tests_path)],
                               verification_required=["pytest -q"],
                               depth=1),
                  receiver_role="tester")

    # 3. Tester — REAL pytest execution (subprocess) on the generated app
    tester = SimulatedAgent("tester", 200)
    mission_reservation = dispatch(tester, "mission:acceptance")
    pytest_run = subprocess.run(
        [sys.executable, "-m", "pytest", "tests/", "-q", "--no-header"],
        cwd=str(work), capture_output=True, text=True, timeout=180,
    )
    tests_pass = pytest_run.returncode == 0 and " no tests ran" not in pytest_run.stdout
    live["pytest_returncode"] = pytest_run.returncode
    live["pytest_tail"] = (pytest_run.stdout or "")[-300:]
    guard.record_usage("agent:tester", tokens_in=50, tokens_out=150,
                       settle_tokens=mission_reservation)
    guard.record_usage("mission:acceptance", tokens_in=50, tokens_out=150,
                       settle_tokens=mission_reservation)
    stages.append(MissionStage("tester", "pytest of generated app",
                               "passed" if tests_pass else "FAILED",
                               [str(tests_path)]))
    if not tests_pass:
        return AcceptanceMissionResult(
            ok=False, stages=stages,
            handoffs=[h.to_dict() for h in ledger.handoffs],
            budgets=guard.report(), stopped_reasons=guard.stopped_reasons(),
            app_dir=work, live_checks=live, simulated_parts=simulated_parts,
        )

    # 4. Reviewer — REAL inspection of the artifact (independent checks)
    reviewer = SimulatedAgent("reviewer", 150)
    mission_reservation = dispatch(reviewer, "mission:acceptance")
    source = app_path.read_text(encoding="utf-8")
    review_findings = []
    if "import hashlib" not in source:
        review_findings.append("missing hashlib import")
    if "eval(" in source or "exec(" in source:
        review_findings.append("dynamic execution found")
    if "def file_digest" not in source or "def main(" not in source:
        review_findings.append("required functions missing")
    reviewer_ok = not review_findings
    guard.record_usage("agent:reviewer", tokens_in=40, tokens_out=110,
                       settle_tokens=mission_reservation)
    guard.record_usage("mission:acceptance", tokens_in=40, tokens_out=110,
                       settle_tokens=mission_reservation)
    stages.append(MissionStage("reviewer", "independent artifact inspection",
                               "approved" if reviewer_ok else f"findings: {review_findings}"))
    ledger.record(AgentHandoff(sender="tester", receiver="reviewer",
                               mission_id="acceptance", completed_work=["suite green"],
                               verification_required=["review"], depth=2),
                  receiver_role="reviewer")

    # 5. Docs specialist
    docs = SimulatedAgent("docs", 120)
    mission_reservation = dispatch(docs, "mission:acceptance")
    readme_path.write_text(README_TEXT, encoding="utf-8")
    guard.record_usage("agent:docs", tokens_in=30, tokens_out=90,
                       settle_tokens=mission_reservation)
    guard.record_usage("mission:acceptance", tokens_in=30, tokens_out=90,
                       settle_tokens=mission_reservation)
    stages.append(MissionStage("docs", "usage instructions", "written",
                               [str(readme_path)]))
    ledger.record(AgentHandoff(sender="reviewer", receiver="docs",
                               mission_id="acceptance", completed_work=["review approved"],
                               artifacts=[str(app_path)], depth=3),
                  receiver_role="docs")

    # 6. Delivery — launch the CLI and VERIFY the output against hashlib
    probe = work / "delivery-probe.txt"
    probe.write_bytes(b"road dog acceptance probe")
    run = subprocess.run(
        [sys.executable, str(app_path), str(probe)],
        capture_output=True, text=True, timeout=60,
    )
    expected = hashlib.sha256(probe.read_bytes()).hexdigest()
    cli_ok = run.returncode == 0 and f"{expected}  {probe}" in run.stdout
    live["cli_returncode"] = run.returncode
    live["cli_expected_sha256"] = expected
    live["cli_stdout"] = run.stdout.strip()
    stages.append(MissionStage("delivery", "CLI launch + output verification",
                               "verified" if cli_ok else "MISMATCH"))

    # 7. Budget enforcement is REAL: prove the guard actually stops work
    stop_proven = False
    try:
        guard.set_budget("agent:developer", Budget(max_tokens=1))
        guard.check_and_reserve("agent:developer", estimated_tokens=999_999)
    except BudgetExceeded:
        stop_proven = True
    live["budget_stop_proven"] = stop_proven

    ok = bool(tests_pass and reviewer_ok and cli_ok and stop_proven)
    return AcceptanceMissionResult(
        ok=ok, stages=stages,
        handoffs=[h.to_dict() for h in ledger.handoffs],
        budgets=guard.report(), stopped_reasons=guard.stopped_reasons(),
        app_dir=work, live_checks=live, simulated_parts=simulated_parts,
    )
